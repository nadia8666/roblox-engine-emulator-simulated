//! `utf8.nfcnormalize` and `utf8.nfdnormalize` as a live client answers them, which is not Unicode's normalization
//! (measured in roblox-sim's 0.747 client and server, tools/parity/probes/utf8_normalize.luau; docs/engine.md
//! "utf8.nfcnormalize and utf8.nfdnormalize"):
//!
//! - nfd writes each code point's full canonical decomposition in place, with no canonical reordering, and a code point
//!   whose decomposition is one code point (a singleton: U+212B, U+2126, U+2000, U+0340, U+F900, ...) is followed by a
//!   U+0000: U+212B is U+0041 U+030A U+0000. A Hangul syllable is its jamo.
//! - nfc decomposes nothing and reorders nothing: each code point composes with the code point before it in the output
//!   when the two have a primary composite (composition exclusions and singletons left out), else it is written. So a
//!   singleton or an excluded composite stays as it is, and a mark that composes with nothing keeps any mark after it
//!   from the letter. A leading consonant and a vowel make a syllable, and any syllable and a trailing consonant from
//!   U+11A7 to U+11C2 add the consonant's index: U+AC01 U+11A8 is U+AC02, U+AC00 U+11A7 is U+AC00, and U+D7A3 U+11A8 is
//!   U+D7A4, past the last syllable.
//! - The data is Unicode 7.0 to 12.1's (the same in each; data/unicode-normalization.rs, generated by
//!   tools/unicode-normalization.mjs). The text is checked as strict UTF-8 first: "End of string is invalid UTF-8" when it
//!   ends inside a sequence that is valid so far, else "String contains invalid UTF-8", raised at the caller.

use std::rc::Rc;

use mlua::prelude::*;

use super::{Ret, raise_at_caller, typeof_value, values};
use crate::Engine;

mod table {
    include!("../../data/unicode-normalization.rs");
}

const S_BASE: u32 = 0xAC00;
const L_BASE: u32 = 0x1100;
const V_BASE: u32 = 0x1161;
const T_BASE: u32 = 0x11A7;
const L_COUNT: u32 = 19;
const V_COUNT: u32 = 21;
const T_COUNT: u32 = 28;
const N_COUNT: u32 = V_COUNT * T_COUNT;
const S_COUNT: u32 = L_COUNT * N_COUNT;

const FIELD: u64 = (1 << 21) - 1;
const PAIR: u64 = (1 << 42) - 1;

// (composite's first test skips every code point below COMPOSING_MIN, so a Hangul vowel or consonant must be above it)
const _: () = assert!(table::COMPOSING_MIN <= V_BASE && table::COMPOSING_MIN <= T_BASE);

/// A code point's canonical decomposition, one level: (first, second), second 0 for a singleton.
fn decomposition(code: u32) -> Option<(u32, u32)> {
    let (first, last) = table::DECOMPOSABLE;
    if code < first || code > last {
        return None;
    }
    let index = table::DECOMPOSITIONS.binary_search_by_key(&code, |entry| (entry >> 42) as u32).ok()?;
    let entry = table::DECOMPOSITIONS[index];
    Some((((entry >> 21) & FIELD) as u32, (entry & FIELD) as u32))
}

/// What `code` makes with the code point before it in nfc's output, if they compose.
fn composite(previous: u32, code: u32) -> Option<u32> {
    if code < table::COMPOSING_MIN {
        return None;
    }
    if (L_BASE..L_BASE + L_COUNT).contains(&previous) && (V_BASE..V_BASE + V_COUNT).contains(&code) {
        return Some(S_BASE + ((previous - L_BASE) * V_COUNT + (code - V_BASE)) * T_COUNT);
    }
    // (any syllable, not only one without a trailing consonant, and U+11A7, which is no consonant: as a client does)
    if (S_BASE..S_BASE + S_COUNT).contains(&previous) && (T_BASE..T_BASE + T_COUNT).contains(&code) {
        return Some(previous + (code - T_BASE));
    }
    let pair = (u64::from(previous) << 21) | u64::from(code);
    let index = table::COMPOSITIONS.binary_search_by_key(&pair, |&entry| table::DECOMPOSITIONS[usize::from(entry)] & PAIR).ok()?;
    Some((table::DECOMPOSITIONS[usize::from(table::COMPOSITIONS[index])] >> 42) as u32)
}

/// Every code point written is a scalar value: the table's, a syllable or a jamo (a syllable plus a trailing consonant's
/// index ends at U+D7BE, below the surrogates).
fn push(out: &mut String, code: u32) {
    out.push(char::from_u32(code).unwrap_or(char::REPLACEMENT_CHARACTER));
}

fn decompose(code: u32, out: &mut String) {
    if (S_BASE..S_BASE + S_COUNT).contains(&code) {
        let index = code - S_BASE;
        push(out, L_BASE + index / N_COUNT);
        push(out, V_BASE + index % N_COUNT / T_COUNT);
        if !index.is_multiple_of(T_COUNT) {
            push(out, T_BASE + index % T_COUNT);
        }
    } else if let Some((first, second)) = decomposition(code) {
        decompose(first, out);
        // (a singleton's second is 0, and a client writes it: U+0000)
        decompose(second, out);
    } else {
        push(out, code);
    }
}

/// `utf8.nfdnormalize` of valid text.
pub fn nfd(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + text.len() / 2);
    for character in text.chars() {
        decompose(u32::from(character), &mut out);
    }
    out
}

/// `utf8.nfcnormalize` of valid text.
pub fn nfc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut last = None;
    for character in text.chars() {
        let code = u32::from(character);
        if let Some(previous) = last {
            if let Some(composed) = composite(previous, code) {
                last = Some(composed);
                continue;
            }
            push(&mut out, previous);
        }
        last = Some(code);
    }
    if let Some(previous) = last {
        push(&mut out, previous);
    }
    out
}

/// The scripts' `utf8.nfcnormalize(text)` (`compose`) and `utf8.nfdnormalize(text)`: a string or a number (in its
/// tostring form), else Luau's argument error naming the function; invalid UTF-8 raises. All at the caller.
pub fn normalize(lua: &Lua, engine: &Rc<Engine>, args: LuaMultiValue, compose: bool) -> Ret {
    let name = if compose { "nfcnormalize" } else { "nfdnormalize" };
    let Some(value) = args.front() else {
        return raise_at_caller(format!("missing argument #1 to '{name}' (string expected)"));
    };
    let text = match value {
        LuaValue::String(text) => text.clone(),
        LuaValue::Integer(_) | LuaValue::Number(_) => match lua.coerce_string(value.clone())? {
            Some(text) => text,
            None => return raise_at_caller(format!("invalid argument #1 to '{name}' (string expected, got number)")),
        },
        other => return raise_at_caller(format!("invalid argument #1 to '{name}' (string expected, got {})", typeof_value(engine, other))),
    };
    let bytes = text.as_bytes();
    if bytes.is_ascii() {
        return Ok(values([LuaValue::String(text.clone())]));
    }
    let valid = match std::str::from_utf8(&bytes) {
        Ok(valid) => valid,
        Err(error) if error.error_len().is_none() => return raise_at_caller("End of string is invalid UTF-8"),
        Err(_) => return raise_at_caller("String contains invalid UTF-8"),
    };
    let out = if compose { nfc(valid) } else { nfd(valid) };
    Ok(values([LuaValue::String(lua.create_string(out)?)]))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text(codes: &[u32]) -> String {
        codes.iter().map(|&code| char::from_u32(code).unwrap()).collect()
    }

    fn codes(text: &str) -> Vec<u32> {
        text.chars().map(u32::from).collect()
    }

    #[test]
    fn the_table_is_sorted_and_holds_the_measured_counts() {
        assert_eq!(table::DECOMPOSITIONS.len(), 2060);
        assert_eq!(table::COMPOSITIONS.len(), 940);
        assert!(table::DECOMPOSITIONS.windows(2).all(|pair| pair[0] >> 42 < pair[1] >> 42));
        let pairs: Vec<u64> = table::COMPOSITIONS.iter().map(|&index| table::DECOMPOSITIONS[usize::from(index)] & PAIR).collect();
        assert!(pairs.windows(2).all(|pair| pair[0] < pair[1]));
        assert_eq!(table::DECOMPOSABLE, (0xC0, 0x2FA1D));
    }

    #[test]
    fn nfd_writes_full_decompositions_in_place_without_reordering() {
        assert_eq!(codes(&nfd(&text(&[0xE9]))), [0x65, 0x301]);
        assert_eq!(codes(&nfd(&text(&[0x1D6]))), [0x75, 0x308, 0x304]);
        assert_eq!(codes(&nfd(&text(&[0x1EC7]))), [0x65, 0x323, 0x302]);
        assert_eq!(codes(&nfd(&text(&[0x1F82]))), [0x3B1, 0x313, 0x300, 0x345]);
        // marks keep their order: Unicode would put the dot below (class 220) before the acute (230)
        assert_eq!(codes(&nfd(&text(&[0x61, 0x301, 0x323]))), [0x61, 0x301, 0x323]);
        assert_eq!(codes(&nfd(&text(&[0xE2, 0x323]))), [0x61, 0x302, 0x323]);
        // compatibility characters and excluded composites: only canonical decompositions apply, exclusions included
        assert_eq!(codes(&nfd(&text(&[0xFB01, 0x2460, 0xBD]))), [0xFB01, 0x2460, 0xBD]);
        assert_eq!(codes(&nfd(&text(&[0x958]))), [0x915, 0x93C]);
        assert_eq!(codes(&nfd(&text(&[0x1E9B]))), [0x17F, 0x307]);
        // Unicode 13.0's U+11938 has no decomposition in a client
        assert_eq!(codes(&nfd(&text(&[0x11938]))), [0x11938]);
    }

    #[test]
    fn nfd_writes_a_nul_after_a_singletons_decomposition() {
        assert_eq!(codes(&nfd(&text(&[0x212B]))), [0x41, 0x30A, 0]);
        assert_eq!(codes(&nfd(&text(&[0x2126, 0x2126]))), [0x3A9, 0, 0x3A9, 0]);
        assert_eq!(codes(&nfd(&text(&[0x2000]))), [0x2002, 0]);
        assert_eq!(codes(&nfd(&text(&[0x340]))), [0x300, 0]);
        assert_eq!(codes(&nfd(&text(&[0xF900]))), [0x8C48, 0]);
        assert_eq!(codes(&nfd(&text(&[0x2FA1D]))), [0x2A600, 0]);
        // U+1F71 is U+03AC, which decomposes: the NUL comes after the whole decomposition
        assert_eq!(codes(&nfd(&text(&[0x1F71, 0x345]))), [0x3B1, 0x301, 0, 0x345]);
    }

    #[test]
    fn nfd_decomposes_hangul_syllables_into_jamo() {
        assert_eq!(codes(&nfd(&text(&[0xAC00]))), [0x1100, 0x1161]);
        assert_eq!(codes(&nfd(&text(&[0xAC01]))), [0x1100, 0x1161, 0x11A8]);
        assert_eq!(codes(&nfd(&text(&[0xD7A3]))), [0x1112, 0x1175, 0x11C2]);
        assert_eq!(codes(&nfd(&text(&[0x3131]))), [0x3131]);
    }

    #[test]
    fn nfc_composes_with_the_code_point_before_it_only() {
        assert_eq!(codes(&nfc(&text(&[0x65, 0x301]))), [0xE9]);
        assert_eq!(codes(&nfc(&text(&[0x75, 0x308, 0x304]))), [0x1D6]);
        assert_eq!(codes(&nfc(&text(&[0xFC, 0x304]))), [0x1D6]);
        assert_eq!(codes(&nfc(&text(&[0xC5, 0x301]))), [0x1FA]);
        assert_eq!(codes(&nfc(&text(&[0x61, 0x323, 0x302]))), [0x1EAD]);
        // no reordering: Unicode's nfc gives U+1EAD and U+1EDB
        assert_eq!(codes(&nfc(&text(&[0x61, 0x302, 0x323]))), [0xE2, 0x323]);
        assert_eq!(codes(&nfc(&text(&[0x6F, 0x301, 0x31B]))), [0xF3, 0x31B]);
        assert_eq!(codes(&nfc(&text(&[0x3B1, 0x345, 0x313, 0x300]))), [0x1FB3, 0x313, 0x300]);
        // nothing past a mark that composes with nothing: Unicode's gives U+00E1 U+0316
        assert_eq!(codes(&nfc(&text(&[0x61, 0x316, 0x301]))), [0x61, 0x316, 0x301]);
        assert_eq!(codes(&nfc(&text(&[0x301, 0x65]))), [0x301, 0x65]);
        // two starters compose too
        assert_eq!(codes(&nfc(&text(&[0xCC6, 0xCC2, 0xCD5]))), [0xCCB]);
    }

    #[test]
    fn nfc_leaves_singletons_and_exclusions_as_they_are() {
        assert_eq!(codes(&nfc(&text(&[0x212B, 0x2126, 0x2000, 0x340, 0xF900]))), [0x212B, 0x2126, 0x2000, 0x340, 0xF900]);
        assert_eq!(codes(&nfc(&text(&[0x212B, 0x301]))), [0x212B, 0x301]);
        assert_eq!(codes(&nfc(&text(&[0x958, 0x344, 0xF73]))), [0x958, 0x344, 0xF73]);
        assert_eq!(codes(&nfc(&text(&[0x915, 0x93C]))), [0x915, 0x93C]);
        assert_eq!(codes(&nfc(&text(&[0x308, 0x301]))), [0x308, 0x301]);
        assert_eq!(codes(&nfc(&text(&[0x2ADD, 0x338]))), [0x2ADD, 0x338]);
        // Unicode 7.0's pairs compose, 13.0's and 16.0's do not
        assert_eq!(codes(&nfc(&text(&[0x11347, 0x1133E]))), [0x1134B]);
        assert_eq!(codes(&nfc(&text(&[0x11935, 0x11930]))), [0x11935, 0x11930]);
        assert_eq!(codes(&nfc(&text(&[0x105D2, 0x307]))), [0x105D2, 0x307]);
        // what nfd wrote reads back with its NUL
        assert_eq!(codes(&nfc(&nfd(&text(&[0x212B])))), [0xC5, 0]);
        assert_eq!(codes(&nfc(&nfd(&text(&[0x1F71])))), [0x3AC, 0]);
    }

    #[test]
    fn nfc_composes_hangul_as_a_client_does() {
        assert_eq!(codes(&nfc(&text(&[0x1100, 0x1161]))), [0xAC00]);
        assert_eq!(codes(&nfc(&text(&[0x1100, 0x1161, 0x11A8]))), [0xAC01]);
        assert_eq!(codes(&nfc(&text(&[0x1112, 0x1175, 0x11C2]))), [0xD7A3]);
        // any syllable takes a trailing consonant, U+11A7 included
        assert_eq!(codes(&nfc(&text(&[0xAC01, 0x11A8]))), [0xAC02]);
        assert_eq!(codes(&nfc(&text(&[0xAC00, 0x11A7]))), [0xAC00]);
        assert_eq!(codes(&nfc(&text(&[0xAC00, 0x11A7, 0x11A8]))), [0xAC01]);
        assert_eq!(codes(&nfc(&text(&[0xAC1B, 0x11A8]))), [0xAC1C]);
        assert_eq!(codes(&nfc(&text(&[0xD7A3, 0x11A8, 0x11A8]))), [0xD7A4, 0x11A8]);
        // outside the ranges nothing composes
        assert_eq!(codes(&nfc(&text(&[0xAC00, 0x11C3]))), [0xAC00, 0x11C3]);
        assert_eq!(codes(&nfc(&text(&[0x1100, 0x1160]))), [0x1100, 0x1160]);
        assert_eq!(codes(&nfc(&text(&[0x115F, 0x1161]))), [0x115F, 0x1161]);
        assert_eq!(codes(&nfc(&text(&[0x1113, 0x1161]))), [0x1113, 0x1161]);
        assert_eq!(codes(&nfc(&text(&[0x1100, 0x1176]))), [0x1100, 0x1176]);
        assert_eq!(codes(&nfc(&text(&[0xAC00, 0x1161]))), [0xAC00, 0x1161]);
    }
}
